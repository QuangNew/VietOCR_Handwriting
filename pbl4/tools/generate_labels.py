"""Generate small Vietnamese text bitmaps; firmware needs no font/filesystem upload.

Run with Python + Pillow. On Windows Segoe UI is used by default; other systems
can pass --regular and --bold paths to fonts containing Vietnamese glyphs.
"""

import argparse
import os
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

PHRASES = {
    "Sleep": ("Đang ngủ...", "Mở app để đánh thức mình nhé."),
    "Awake": ("Mình đã thức!", "Chào bạn, mình ở đây rồi."),
    "Idle": ("Mình sẵn sàng!", "Chờ ảnh tiếp theo của bạn nhé."),
    "Received": ("Đã nhận ảnh!", "Mình chờ bắt đầu nhận diện."),
    "Processing": ("Đang đọc chữ...", "Bạn chờ mình một chút nhé."),
    "Done": ("Xong rồi, bạn ơi!", "Văn bản đã sẵn sàng."),
    "Error": ("Có lỗi rồi...", "Kiểm tra ảnh hoặc thử lại nhé."),
}


def bitmap(text, font):
    bounds = font.getbbox(text)
    width, height = bounds[2] - bounds[0] + 4, bounds[3] - bounds[1] + 4
    image = Image.new("L", (width, height))
    ImageDraw.Draw(image).text((2-bounds[0], 2-bounds[1]), text, font=font, fill=255)
    data = []
    for y in range(height):
        for start in range(0, width, 8):
            value = sum(1 << bit for bit in range(min(8, width-start)) if image.getpixel((start+bit, y)) >= 128)
            data.append(value)
    return width, height, data


def main():
    fonts = Path(os.environ.get("WINDIR", "C:/Windows")) / "Fonts"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--regular", type=Path, default=fonts / "segoeui.ttf")
    parser.add_argument("--bold", type=Path, default=fonts / "segoeuib.ttf")
    args = parser.parse_args()
    regular = ImageFont.truetype(str(args.regular), 13)
    bold = ImageFont.truetype(str(args.bold), 19)
    output = ["// Generated by tools/generate_labels.py. Do not edit bitmap bytes by hand.",
              "#pragma once", "#include <Arduino.h>", "namespace assistant_labels {",
              "struct Bitmap { const uint8_t* data; uint16_t width; uint16_t height; };"]
    size = 0
    for name, phrases in PHRASES.items():
        for part, text, font in (("Title", phrases[0], bold), ("Detail", phrases[1], regular)):
            width, height, data = bitmap(text, font)
            if width > 284 or height > (25 if part == "Title" else 21):
                raise ValueError(f"Label does not fit: {text} ({width}x{height})")
            symbol = f"k{name}{part}"
            output.extend([f"// {text}", f"static const uint8_t {symbol}Data[] PROGMEM = {{"])
            output.extend("  " + ", ".join(f"0x{value:02x}" for value in data[i:i+16]) + "," for i in range(0, len(data), 16))
            output.extend(["};", f"static const Bitmap {symbol} = {{{symbol}Data, {width}, {height}}};"])
            size += len(data)
    output.append("}  // namespace assistant_labels")
    destination = Path(__file__).resolve().parents[1] / "include" / "assistant_labels.h"
    destination.write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"Generated {len(PHRASES)*2} labels, {size} bytes: {destination.name}")


if __name__ == "__main__":
    main()
