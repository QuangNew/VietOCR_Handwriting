"""Create a UI-independent server model release from the AI team's tested files.

Local copies only. Never downloads weights or changes the desktop implementation.
"""
import hashlib
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / "VietHandOCR_API_Release"


def sync():
    config = json.loads((SOURCE / "model/model_config.json").read_text(encoding="utf-8"))
    name = config["weights_file"]
    if Path(name).name != name:
        raise ValueError("Unsafe model filename")
    weights = SOURCE / "model" / name
    digest = hashlib.file_digest(weights.open("rb"), "sha256").hexdigest()
    if digest != config["weights_sha256"]:
        raise ValueError("Model SHA-256 does not match the AI team's release")
    target = ROOT / "models" / config["name"]
    target.mkdir(parents=True, exist_ok=True)
    for filename in (name, "model_config.json"):
        shutil.copy2(SOURCE / "model" / filename, target / filename)
    core = ROOT / "worker/core"
    core.mkdir(parents=True, exist_ok=True)
    shutil.copy2(SOURCE / "viethandocr_lite.py", core / "recognizer.py")
    shutil.copy2(SOURCE / "LICENSE_VietOCR.txt",core / "LICENSE_VietOCR.txt")
    # Extract only the existing, tested preprocessing and line splitter. No Tk,
    # Bleak or desktop entrypoint is imported by the server worker.
    ai = (SOURCE / "AI.py").read_text(encoding="utf-8")
    dip = ai[ai.index("class VietOCR_DIP_Pipeline:"):ai.index("# 3. CORE API CLASS")]
    dip = dip.rsplit("# =========================================================================", 1)[0]
    service = (ROOT / "worker/core/preprocessing.py").read_text(encoding="utf-8")
    splitter = service[service.index("def split_text_lines("): ]
    (core / "preprocessing.py").write_text(
        '# Generated by tools/sync_model.py from the AI team pipeline.\n'
        'import os\nimport warnings\nimport cv2\nimport numpy as np\n\n' + dip + "\n\n" + splitter,
        encoding="utf-8")
    provenance = {"name": config["name"], "weights_sha256": digest,
                  "source_files": {str(p.relative_to(SOURCE)): hashlib.sha256(p.read_bytes()).hexdigest()
                                   for p in [SOURCE / "AI.py", SOURCE / "viethandocr_lite.py",
                                             SOURCE / "model/model_config.json"]}}
    (target / "provenance.json").write_text(json.dumps(provenance, indent=2), encoding="utf-8")
    print(f"Server model ready: {config['name']}, {weights.stat().st_size / 1048576:.1f} MiB, SHA-256 verified")


if __name__ == "__main__":
    sync()
